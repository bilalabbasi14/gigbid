def build_persona(pid: str, n_projects: int, n_proposals: int, n_reviews: int, seed: int) -> None:
    p = PERSONAS[pid]
    rng = random.Random(f"{seed}:{pid}")
    d = OUT / pid
    (d / "case_studies").mkdir(parents=True, exist_ok=True)
    (d / "repos").mkdir(parents=True, exist_ok=True)
    print(f"== {pid}: {p['name']}")

    projects = gen_projects(pid, p, n_projects, rng)
    (d / "projects.json").write_text(json.dumps(projects, indent=2, ensure_ascii=False), encoding="utf-8")
    print(f"  projects: {len(projects)}")

    for i, proj in enumerate(projects):
        md = gen_case_study(pid, p, proj, style=i)
        front = f"---\nproject_id: {proj['id']}\nyear: {proj['year']}\nclient_industry: {proj['client_industry']}\nskills: {json.dumps(proj['skills'])}\nlibraries: {json.dumps(proj.get('libraries', []))}\n---\n\n"
        (d / "case_studies" / f"cs_{i + 1:02d}.md").write_text(front + md.strip() + "\n", encoding="utf-8")
        print(f"  case study {proj['id']} ok")
        if proj.get("has_repo"):
            files = gen_repo(pid, p, proj)
            rd = d / "repos" / proj["repo_slug"]
            for rel, content in files.items():
                fp = rd / rel.lstrip("/")
                fp.parent.mkdir(parents=True, exist_ok=True)
                fp.write_text(content.rstrip() + "\n", encoding="utf-8")
            (rd / ".project_id").write_text(proj["id"] + "\n", encoding="utf-8")
            print(f"  repo {proj['repo_slug']} ({len(files)} files) ok")

    cv = gen_cv(pid, p, projects)
    (d / "cv.md").write_text(cv.strip() + "\n", encoding="utf-8")
    write_pdf(cv, d / "cv.pdf")
    print("  cv ok")

    reviews = gen_reviews(pid, p, projects, n_reviews)
    with (d / "reviews.jsonl").open("w", encoding="utf-8") as f:
        for i, r in enumerate(reviews):
            r["review_id"] = f"{pid}_rev_{i + 1:02d}"
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    print(f"  reviews: {len(reviews)}")

    jobs = [json.loads(line) for line in gzip.open(SEED_JOBS, "rt", encoding="utf-8")]
    jobs = [j for j in jobs if j["persona"] == pid and j["signal_score"] >= 3]
    proposals = gen_proposals(pid, p, projects, jobs, n_proposals, rng)
    with (d / "proposals.jsonl").open("w", encoding="utf-8") as f:
        for it in proposals:
            f.write(json.dumps(it, ensure_ascii=False) + "\n")
    counts = {k: sum(1 for x in proposals if x.get("outcome") == k) for k in ("won", "replied", "ignored")}
    print(f"  proposals: {len(proposals)} {counts}")

    (d / "profile.json").write_text(json.dumps({"persona_id": pid, **p, "synthetic": True, "generated_by": "data/scripts/gen_personas.py"}, indent=2, ensure_ascii=False), encoding="utf-8")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--persona", choices=list(PERSONAS), default=None)
    ap.add_argument("--projects", type=int, default=15)
    ap.add_argument("--proposals", type=int, default=60)
    ap.add_argument("--reviews", type=int, default=12)
    ap.add_argument("--seed", type=int, default=2026)
    args = ap.parse_args()
    for pid in [args.persona] if args.persona else list(PERSONAS):
        build_persona(pid, args.projects, args.proposals, args.reviews, args.seed)


if __name__ == "__main__":
    main()
