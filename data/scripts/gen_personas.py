"""Generate the three synthetic freelancer persona corpora used for RAG.

Why synthetic: the starter kit did not include the persona corpora. These are generated by an
open model, seeded from real job categories, and are clearly labelled SYNTHETIC in
docs/DATA_CARD.md. Everything is written under data/personas/<persona>/ and committed; the raw
LLM responses are cached under data/personas/_generated_cache/ (git-ignored) so a run can resume.

Per persona:
  profile.json                      name, headline, rates, years, skills
  cv.md + cv.pdf                    CV (PDF rendered from the markdown)
  projects.json                     the project catalogue every other artefact is derived from
  case_studies/cs_NN.md             one per project (the "prose" view)
  repos/<slug>/README.md + code     for a subset of projects (the "code" view, skills implied)
  reviews.jsonl                     client reviews
  proposals.jsonl                   past proposals with outcome labels won | replied | ignored,
                                    each tied to a real job from gigsim/seed and to project ids

Run: uv run python -m data.scripts.gen_personas [--persona ai_ml] [--projects 15] [--proposals 60]
"""

